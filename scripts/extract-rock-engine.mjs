import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const root = new URL('../', import.meta.url);
const source = readFileSync(new URL('data/assets/rocks/asterra/ASTERRA_Gerador_Rochas_v2.3.html', root));
const html = source.toString('utf8');
const section = (start, end) => {
  const from = html.indexOf(start);
  const to = html.indexOf(end, from);
  if (from < 0 || to < 0) throw new Error(`Marcadores do gerador de rochas ausentes: ${start}, ${end}`);
  return html.slice(from, to);
};

// Copy original code verbatim. Only the demo UI and legacy bitmap comparison are excluded.
const body = section('const TILE=16,', 'SPRITES_LEGACY.pedra=')
  + section('const clamp=(v,a,b)', 'let last={};');
const header = '// Generated by scripts/extract-rock-engine.mjs. Do not edit original engine code.\n';
const exports = '\nexport { TILE, biomeProfiles, rarityProfiles, rng, hash, weightedChoice, chooseRarity, sizeProfile, footprintAt, depositData, outcropSize, rockSprite, drawOutcrop };\n';
const output = header + body + exports;

const defaults = {};
for (const match of html.matchAll(/<select id="([^"]+)"[^>]*>([\s\S]*?)<\/select>/g)) {
  const options = [...match[2].matchAll(/<option value="([^"]+)"([^>]*)>/g)];
  defaults[match[1]] = (options.find((option) => /\bselected\b/.test(option[2])) ?? options[0])[1];
}
for (const match of html.matchAll(/<input\b([^>]+)>/g)) {
  const attributes = Object.fromEntries([...match[1].matchAll(/(\w+)="([^"]*)"/g)].map((attribute) => [attribute[1], attribute[2]]));
  if (!attributes.id) continue;
  if (attributes.type === 'range') {
    // Match the browser's range sanitization (e.g. value 42, step 5 becomes 40).
    const min = Number(attributes.min ?? 0);
    const max = Number(attributes.max ?? 100);
    const step = Number(attributes.step ?? 1);
    const value = min + Math.round((Number(attributes.value) - min) / step) * step;
    defaults[attributes.id] = Math.max(min, Math.min(max, value)) / 100;
  }
  if (attributes.type === 'number') defaults[attributes.id] = Number(attributes.value);
  if (attributes.type === 'checkbox') defaults[attributes.id] = /\bchecked\b/.test(match[1]);
}
const provenance = {
  source: 'data/assets/rocks/asterra/ASTERRA_Gerador_Rochas_v2.3.html',
  sourceSha256: createHash('sha256').update(source).digest('hex'),
  engineSha256: createHash('sha256').update(output).digest('hex'),
  extraction: 'Verbatim core sections; excluded demo controls, exports and embedded legacy bitmap comparison. ES module exports appended.',
};

writeFileSync(new URL('src/modules/geosphere/rendering/rocks/legacy-engine.js', root), output);
writeFileSync(new URL('src/modules/geosphere/rendering/rocks/legacy-defaults.json', root), JSON.stringify(defaults, null, 2) + '\n');
writeFileSync(new URL('src/modules/geosphere/rendering/rocks/provenance.json', root), JSON.stringify(provenance, null, 2) + '\n');
console.log(`Gerador de rochas v2.3 extraído; SHA-256 ${provenance.engineSha256}`);
